const MODE_PROMPT: Record<DreamMode, string> = {
    casual: CASUAL_PROMPT,
    deep: DEEP_PROMPT,
};

export function getChatSystemPrompt(mode: DreamMode = "deep"): string {
    return MODE_PROMPT[mode];
}
